package methods;

public class StringCasing {
    public static void main(String[] args) {
        String normalTest = "I am a Java Programmer.";

        String upperText = normalTest.toUpperCase();

        String lowerTest = normalTest.toLowerCase();

        System.out.println("Upper : " + upperText);
        System.out.println("Lower : " + lowerTest);
        
    }
    
}
